CREATE TABLE combinedlibrary (
    acession_no BIGINT,
    book_title TEXT,
    author TEXT,
    price_inr VARCHAR(50),
    price_dollar VARCHAR(50),
    price_euro VARCHAR(50),
    publisher TEXT,
    issued VARCHAR(50),
    number_donated INT,
    book_shelf_no VARCHAR(50),
    compartment_no VARCHAR(50),
    no_copies INT
);